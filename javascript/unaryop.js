// Unary Operator - value
// 1.increment ++ - it is used to increment by one
// pre ++a post a++

// Task1
var a=10;
console.log(a++);
console.log(++a);

// Task2
var a=10
var b=++a
console.log(++a);
console.log(b++);
var c=++b
console.log(a+b+c);

// 2.decrement -- - it is used to decrement by one
// Task3
var a=10
var b=--a
console.log(--a);
console.log(b--);
var c=--b
console.log(b++);
console.log(a+b+c);