// WAP to display menu of food items using switch case

var ch = 3;

switch(ch)
{
    case 1: console.log("Pizza");
            break;

    case 2:console.log("Burger");
            break;

    case 3: console.log("Sandwich");
            break;

    case 4:console.log("Dosa");
         break;

    case 5: console.log("Pav Bhaji");
         break;

    default:
        console.log("Invalid Choice");
}