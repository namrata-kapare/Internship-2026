// WAP to program to check the vowel using switch

var ch = 'b';

switch(ch)
{
    case 'a':
    case 'e':
    case 'i':
    case 'o':
    case 'u':
    case 'A':
    case 'E':
    case 'I':
    case 'O':
    case 'U':
             console.log("Vowel");
             break;

    default:
              console.log("Consonant");
}