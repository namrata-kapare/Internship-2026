
// other operations on the array

// value add from last index of array

let fruits = ["Apple", "Mango"];
fruits.push("Banana");
console.log(fruits);

// delete value from last index of array

let fruits = ["Apple", "Mango", "Banana"];
fruits.pop();
console.log(fruits);

// delete value from first index of array

let fruits = ["Apple", "Mango", "Banana"];
fruits.shift();
console.log(fruits);

// add value from first index of array

let fruits = ["Mango", "Banana"];
fruits.unshift("Apple");
console.log(fruits);